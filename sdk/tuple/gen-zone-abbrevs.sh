#!/bin/sh
# Writes zones_gen.go: the time zone abbreviations Tarantool knows, from
# src/lib/tzcode/timezones.h of Tarantool, given as the first argument or
# fetched from GitHub. The ambiguous ones, which Tarantool does not take in
# a text, are a map of their own.
set -eu

src=${1:-}
if [ -z "$src" ]; then
	src=$(mktemp)
	trap 'rm -f "$src"' EXIT
	curl -fsSL -o "$src" \
		https://raw.githubusercontent.com/tarantool/tarantool/master/src/lib/tzcode/timezones.h
fi

{
	echo '// Code generated by gen-zone-abbrevs.sh; DO NOT EDIT.'
	echo
	echo 'package tuple'
	echo
	echo '// zoneAbbrevOffsets maps a time zone abbreviation Tarantool knows to its'
	echo '// offset from UTC in minutes.'
	echo 'var zoneAbbrevOffsets = map[string]int{'
	grep '^ZONE_ABBREV(' "$src" | grep -v TZ_AMBIGUOUS |
		sed -E 's/^ZONE_ABBREV\( *[0-9]+, *(-?[0-9]+), *"([^"]+)".*/\t"\2": \1,/'
	echo '}'
	echo
	echo '// ambiguousZoneAbbrevs are the time zone abbreviations Tarantool knows'
	echo '// but does not take in a text, as they name more than one zone.'
	echo 'var ambiguousZoneAbbrevs = map[string]bool{'
	grep '^ZONE_ABBREV(' "$src" | grep TZ_AMBIGUOUS |
		sed -E 's/^ZONE_ABBREV\( *[0-9]+, *-?[0-9]+, *"([^"]+)".*/\t"\1": true,/'
	echo '}'
} > zones_gen.go
gofmt -w zones_gen.go
