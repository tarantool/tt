package wasm

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/tarantool/tt/v3/cli/manifest"
)

const testManifest = `manifest_version = "0.1"

[package]
name = "notes"

[platform]
tarantool = ">=3.6.0"
tt = ">=3.0.0"

[dependencies]
wasm = { version = "0.1.0", registry = ".tarantool/registry" }

[components.app]
path = "app"

[components.router]
path = "router"
include = ["dist/app.wasm"]

[components.router.build]
backend = "shell"
command = "tarawasm"
args = ["all"]
`

// writeProject writes a package with a Lua component and a tarawasm one
// whose SDK lock pins sdkVersion, and returns its directory.
func writeProject(t *testing.T, sdkVersion string) string {
	t.Helper()

	project := t.TempDir()
	write := func(rel, content string) {
		path := filepath.Join(project, rel)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), dirPerm))
		require.NoError(t, os.WriteFile(path, []byte(content), filePerm))
	}

	write(manifestFileName, testManifest)
	write("app/init.lua", "return {}\n")
	write("router/tarawasm.json", `{"language": "python", "world": "app", `+
		`"source": "main.py", "output": "dist/app.wasm"}`)
	write("router/tarawasm.tarantool.lock.json", `{"version": "`+sdkVersion+`"}`)

	return project
}

func TestFindComponents(t *testing.T) {
	t.Parallel()

	project := writeProject(t, "0.1.0")

	components, err := FindComponents(project)
	require.NoError(t, err)
	assert.Equal(t, []Component{{
		Name: "router", Dir: filepath.Join(project, "router"), Language: "python",
		Output: "dist/app.wasm", SDKVersion: "0.1.0",
	}}, components)

	version, err := DeclaredVersion(project)
	require.NoError(t, err)
	assert.Equal(t, "0.1.0", version)
	assert.Empty(t, SDKWarnings(project))
}

func TestSDKMismatch(t *testing.T) {
	t.Parallel()

	project := writeProject(t, "0.0.9")

	warnings := SDKWarnings(project)
	require.Len(t, warnings, 1)
	assert.Contains(t, warnings[0], `component "router" is built with the tarantool-wasm 0.0.9 SDK`)
}

func TestComponentLanguages(t *testing.T) {
	t.Parallel()

	components := []Component{{Name: "a", Dir: "", Language: "rust", Output: "", SDKVersion: ""}}
	assert.Equal(t, []string{"python", "rust"}, componentLanguages(components, "python"))
	assert.Equal(t, []string{"rust"}, componentLanguages(components, "rust"))
}

func TestDeclareComponent(t *testing.T) {
	t.Parallel()

	project := writeProject(t, "0.1.0")

	require.NoError(t, declareComponent(project, "api", "wasm/api", "dist/api.wasm"))

	data, err := os.ReadFile(filepath.Join(project, manifestFileName))
	require.NoError(t, err)

	man, _, err := manifest.ParseManifest(data)
	require.NoError(t, err)

	api := man.Components["api"]
	assert.Equal(t, "wasm/api", api.Path)
	assert.Equal(t, []string{"dist/api.wasm"}, api.Include)
	require.NotNil(t, api.Build)
	assert.Equal(t, "tarawasm", api.Build.Command)
	assert.Equal(t, []string{"all"}, api.Build.Args)
	assert.Contains(t, string(data), testManifest, "the manifest is appended to, not rewritten")
}

func TestGitignore(t *testing.T) {
	t.Parallel()

	assert.Equal(t, "# Generated by tarawasm, and rebuilt by tarawasm all.\n"+
		".tarawasm/\ndist/\n# Where the tools tt installed are, on this machine.\n"+
		"tarawasm.local.json\n__pycache__/\nwit_world/\ncomponentize_py_*\npoll_loop.py\n",
		gitignore("python"))
	assert.Contains(t, gitignore("rust"), "target/\n")
}
