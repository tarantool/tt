package distbuild

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"text/template"

	"github.com/tarantool/tt/sdk"
	"github.com/tarantool/tt/v3/cli/manifest"
)

// generatedHeader marks the files the build writes.
const generatedHeader = "// Code generated by tt binary build tt. DO NOT EDIT.\n"

// mainModule is the module path of the generated main module.
const mainModule = "ttdistribution"

// zeroTime is the time of the placeholder pseudo-version a replaced module
// is required at.
const zeroTime = "00010101000000-000000000000"

// integrityPackage is the package of the integrity providers, in the
// repository of tt's own core.
const integrityPackage = "github.com/tarantool/tt/sdk/integrity"

// majorSuffixRe matches the major version suffix of a module path.
var majorSuffixRe = regexp.MustCompile(`/v([2-9]|[1-9][0-9]+)$`)

// notIdent matches what may not be in a Go identifier.
var notIdent = regexp.MustCompile(`[^A-Za-z0-9_]`)

// requirement is one module the main module requires, and where it comes
// from.
type requirement struct {
	// Module is the module path.
	Module string
	// Version is the version required.
	Version string
	// Replace is what the module is replaced with: a directory, or a
	// module path and version. Empty: not replaced.
	Replace string
}

// requirements lists what the main module requires and replaces: the core,
// the modules of its repository and the tt modules. A local tt module that
// is a module of the core's repository takes the place of the pinned one.
func requirements(base core, modules []module) ([]requirement, []requirement, error) {
	required := map[string]requirement{}
	replaced := map[string]requirement{}

	coreReq := requirement{Module: base.Module, Version: base.Version, Replace: ""}
	if base.Dir != "" {
		coreReq.Version = placeholderVersion(base.Module)
		replaced[base.Module] = requirement{
			Module: base.Module, Version: "", Replace: dirReplace(base.Dir),
		}
	}

	required[base.Module] = coreReq

	for _, repo := range base.Repository {
		target := dirReplace(repo.Dir)
		if repo.Dir == "" {
			target = repo.Module + " " + repo.Version
		}

		replaced[repo.Module] = requirement{Module: repo.Module, Version: "", Replace: target}
	}

	for _, mod := range modules {
		req := requirement{Module: mod.Module, Version: mod.Version, Replace: ""}

		switch {
		case mod.Dir != "":
			req.Version = placeholderVersion(mod.Module)
			replaced[mod.Module] = requirement{
				Module: mod.Module, Version: "", Replace: dirReplace(mod.Dir),
			}
		case base.inRepository(mod.Module):
			req.Version = placeholderVersion(mod.Module)
		}

		prev, ok := required[mod.Module]
		if ok && prev != req {
			return nil, nil, sdk.Errorf(sdk.ExitFailure,
				"dependencies.%s: module %s is listed twice, as %s and as %s",
				mod.Name, mod.Module, describeReq(prev), describeReq(req))
		}

		required[mod.Module] = req
	}

	return sortedReqs(required), sortedReqs(replaced), nil
}

// generateGoMod writes the go.mod of the main module.
func generateGoMod(base core, modules []module) ([]byte, error) {
	required, replaced, err := requirements(base, modules)
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer

	buf.WriteString(generatedHeader)
	buf.WriteString("\nmodule " + mainModule + "\n")

	if base.GoVersion != "" {
		buf.WriteString("\ngo " + base.GoVersion + "\n")
	}

	buf.WriteString("\nrequire (\n")

	for _, req := range required {
		fmt.Fprintf(&buf, "\t%s %s\n", req.Module, req.Version)
	}

	buf.WriteString(")\n")

	if len(replaced) > 0 {
		buf.WriteString("\nreplace (\n")

		for _, rep := range replaced {
			fmt.Fprintf(&buf, "\t%s => %s\n", rep.Module, rep.Replace)
		}

		buf.WriteString(")\n")
	}

	return buf.Bytes(), nil
}

// versionInfo is the version of a distribution, as core.VersionInfo has it.
type versionInfo struct {
	Tag             string
	Commit          string
	CommitsSinceTag int
	Label           string
}

// known reports whether the version says anything.
func (v versionInfo) known() bool {
	return v.Tag != "" || v.Commit != ""
}

// mainSpec is what the generated main package is made of.
type mainSpec struct {
	// CoreModule is the module of the core.
	CoreModule string
	// Modules are the tt modules, in the order of their names.
	Modules []module
	// Options are the options of the distribution.
	Options manifest.DistributionOptions
	// Version is the version of the distribution.
	Version versionInfo
}

// mainImport is an import of the generated main package.
type mainImport struct {
	Alias string
	Path  string
}

// mainEntry is an entry of the table of modules.
type mainEntry struct {
	Name string
	Ctor string
}

// mainData is what the template of the main package is filled with.
type mainData struct {
	Header     string
	Imports    []mainImport
	Entries    []mainEntry
	Flavour    bool
	Title      string
	Edition    string
	Version    versionInfo
	Integrity  bool
	NoExternal bool
}

// mainTemplate is the main package of a distribution.
var mainTemplate = template.Must(template.New("main").Parse(`{{.Header}}
// Command tt is a distribution of tt built from tt.manifest.toml.
package main

import (
	"os"
{{range .Imports}}
	{{if .Alias}}{{.Alias}} {{end}}{{printf "%q" .Path}}{{end}}
)

func main() {
	os.Exit(core.Main(
		core.Modules{
{{- range .Entries}}
			{{printf "%q" .Name}}: {{.Ctor}},
{{- end}}
		},
{{- if .Flavour}}
		core.WithFlavour(core.Flavour{
			Title:   {{printf "%q" .Title}},
			Edition: {{printf "%q" .Edition}},
			Version: core.VersionInfo{
				Tag:             {{printf "%q" .Version.Tag}},
				Commit:          {{printf "%q" .Version.Commit}},
				CommitsSinceTag: {{.Version.CommitsSinceTag}},
				Label:           {{printf "%q" .Version.Label}},
			},
		}),
{{- end}}
{{- if .Integrity}}
		core.WithIntegrity(integrity.NewRSAProvider()),
{{- end}}
{{- if .NoExternal}}
		core.WithoutExternalModules(),
{{- end}}
	))
}
`))

// generateMain writes the main package of a distribution: the table of its
// modules, by name, handed to core.Main with the options the manifest sets.
// The output depends on nothing but spec: the same manifest is the same
// source.
func generateMain(spec mainSpec) ([]byte, error) {
	data := mainData{
		Header:  generatedHeader,
		Imports: []mainImport{{Alias: "", Path: spec.CoreModule + "/core"}},
		Entries: nil,
		Flavour: spec.Options.Title != "" || spec.Options.Edition != "" ||
			spec.Version.known(),
		Title:      spec.Options.Title,
		Edition:    spec.Options.Edition,
		Version:    spec.Version,
		Integrity:  spec.Options.IntegrityValue() == manifest.IntegrityRSA,
		NoExternal: !spec.Options.ExternalModulesValue(),
	}

	if data.Integrity {
		data.Imports = append(data.Imports, mainImport{Alias: "", Path: integrityPackage})
	}

	if spec.Options.BuiltinValue() {
		data.Entries = append(data.Entries, mainEntry{Name: "builtin", Ctor: "core.Builtin"})
	}

	taken := map[string]bool{"os": true, "core": true, "integrity": true, "main": true}

	for _, mod := range spec.Modules {
		alias := importAlias(mod.Name, taken)

		data.Imports = append(data.Imports, mainImport{Alias: alias, Path: mod.Package})
		data.Entries = append(data.Entries,
			mainEntry{Name: mod.Name, Ctor: alias + "." + mod.Symbol})
	}

	slices.SortFunc(data.Imports, func(a, b mainImport) int {
		return strings.Compare(a.Path, b.Path)
	})
	slices.SortFunc(data.Entries, func(a, b mainEntry) int {
		return strings.Compare(a.Name, b.Name)
	})

	var buf bytes.Buffer

	err := mainTemplate.Execute(&buf, data)
	if err != nil {
		return nil, fmt.Errorf("generating main.go: %w", err)
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generating main.go: %w", err)
	}

	return src, nil
}

// importAlias returns the alias the package of the module name is imported
// under: the name made an identifier, unique among taken.
func importAlias(name string, taken map[string]bool) string {
	base := "mod_" + notIdent.ReplaceAllString(name, "_")

	alias := base
	for i := 2; taken[alias]; i++ {
		alias = base + "_" + strconv.Itoa(i)
	}

	taken[alias] = true

	return alias
}

// placeholderVersion is the version a module replaced with something else
// is required at: the zero pseudo-version of its major version.
func placeholderVersion(path string) string {
	major := "v0"
	if match := majorSuffixRe.FindStringSubmatch(path); match != nil {
		major = "v" + match[1]
	}

	return major + ".0.0-" + zeroTime
}

// dirReplace is the target of a replace directive with a directory.
func dirReplace(dir string) string {
	if strings.ContainsAny(dir, " \t\"'`") {
		return strconv.Quote(dir)
	}

	return dir
}

// describeReq describes a requirement in an error.
func describeReq(req requirement) string {
	if req.Version == "" || strings.HasSuffix(req.Version, zeroTime) {
		return "a module without a version"
	}

	return req.Version
}

// sortedReqs returns the requirements in reqs ordered by module path.
func sortedReqs(reqs map[string]requirement) []requirement {
	out := make([]requirement, 0, len(reqs))
	for _, req := range reqs {
		out = append(out, req)
	}

	slices.SortFunc(out, func(a, b requirement) int { return strings.Compare(a.Module, b.Module) })

	return out
}
