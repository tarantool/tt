package version_test

import (
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/tarantool/tt/v3/cli/manifest"
	"github.com/tarantool/tt/v3/cli/manifest/version"
)

func TestGenerateRocksLua(t *testing.T) {
	t.Parallel()

	got := version.GenerateRocksLua(version.RocksLua{
		Package: "myapp",
		Version: version.Version{SemVer: "1.2.0", Commit: "abc123", Dirty: false, Flavor: "ce"},
		Product: "default",
		Rocks: []manifest.LockDependency{
			{Name: "vshard", Version: "0.1.27-1", Source: "registry"},
			{Name: "mylib", Version: "0.3.0", Source: "path", Path: "../mylib"},
			{Name: "crud", Version: "1.5.2-1", Source: "registry"},
			{Name: "lua-term", Version: "0.8-1", Source: "registry"},
			{Name: "leaf", Version: "", Source: "path", Path: "../leaf"},
		},
	})

	assert.Equal(t, `-- Generated by tt package build. Do not edit.
return {
    package = { name = "myapp", version = "1.2.0", commit = "abc123", dirty = false },
    product = "default",
    rocks = {
        crud         = { version = "1.5.2-1", source = "registry" },
        leaf         = { version = "", source = "path" },
        ["lua-term"] = { version = "0.8-1", source = "registry" },
        mylib        = { version = "0.3.0", source = "path" },
        vshard       = { version = "0.1.27-1", source = "registry" },
    },
}
`, got)
}

func TestGenerateRocksLuaEmptyClosure(t *testing.T) {
	t.Parallel()

	got := version.GenerateRocksLua(version.RocksLua{
		Package: "my-app",
		Version: version.Version{SemVer: "0.1.0-dev.2", Commit: "deadbee", Dirty: true},
		Product: "tools",
		Rocks:   nil,
	})

	assert.Equal(t, `-- Generated by tt package build. Do not edit.
return {
    package = { name = "my-app", version = "0.1.0-dev.2", commit = "deadbee", dirty = true },
    product = "tools",
    rocks = {},
}
`, got)
}

// TestGenerateRocksLuaKeys pins which rock names are written as bare keys:
// Lua names alone, so a dash, a dot, a leading digit or a keyword takes the
// bracketed form.
func TestGenerateRocksLuaKeys(t *testing.T) {
	t.Parallel()

	rocks := []manifest.LockDependency{
		{Name: "a.b", Version: "1", Source: "registry"},
		{Name: "1x", Version: "1", Source: "registry"},
		{Name: "end", Version: "1", Source: "registry"},
		{Name: "snake_case", Version: "1", Source: "registry"},
	}

	got := version.GenerateRocksLua(version.RocksLua{
		Package: "p", Version: version.Version{}, Product: "default", Rocks: rocks,
	})

	assert.Contains(t, got, `        ["1x"]     = {`)
	assert.Contains(t, got, `        ["a.b"]    = {`)
	assert.Contains(t, got, `        ["end"]    = {`)
	assert.Contains(t, got, `        snake_case = {`)
}

// TestGenerateRocksLuaEscapes pins that a value cannot break out of its
// literal: quotes and backslashes are escaped, control characters, a newline
// among them, take the decimal escape.
func TestGenerateRocksLuaEscapes(t *testing.T) {
	t.Parallel()

	got := version.GenerateRocksLua(version.RocksLua{
		Package: `we"ird\name`,
		Version: version.Version{SemVer: "1.0.0\n", Commit: "a\tb"},
		Product: "default",
		Rocks:   []manifest.LockDependency{{Name: "x\"y", Version: "1\r", Source: "registry"}},
	})

	assert.Contains(t, got, `name = "we\"ird\\name", version = "1.0.0\010", commit = "a\009b"`)
	assert.Contains(t, got, `["x\"y"] = { version = "1\013", source = "registry" }`)
}
