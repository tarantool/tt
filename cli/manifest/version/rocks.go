package version

import (
	"cmp"
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/tarantool/tt/v3/cli/manifest"
)

// luaIdentRe is a Lua name: a key matching it, and no keyword, is written
// bare in a table constructor.
var luaIdentRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// luaKeywords are the reserved words of LuaJIT, goto included: a key named
// so is written in brackets, as any other key that is no Lua name.
var luaKeywords = []string{
	"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto",
	"if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until",
	"while",
}

// RocksLua is what rocks.lua describes: the package that was built, the
// product of it and the closure of that product.
type RocksLua struct {
	// Package is the name of the package.
	Package string
	// Version is the derived version of the package.
	Version Version
	// Product is the name of the product built.
	Product string
	// Rocks is the closure of the product as the lock pins it: the
	// dependencies, those of the dependencies included, with no
	// [dev_dependencies].
	Rocks []manifest.LockDependency
}

// GenerateRocksLua renders the rocks.lua descriptor of desc: a Lua module
// returning a table of the package, the product and every rock of the closure
// by name, with the version and the source the lock records for it. The rocks
// are sorted by name and nothing in it depends on the time of the build, so
// the same lock and version render the same text. The build drops the result
// at .rocks/share/tarantool/<package>/rocks.lua beside version.lua; this
// function only produces the text.
//
// Generation is on by default and disabled per package via
// [package].generate_rocks_lua = false; that gate lives in the build, which
// consults manifest.Package.GenerateRocksLuaValue before calling here.
func GenerateRocksLua(desc RocksLua) string {
	var buf strings.Builder

	buf.WriteString("-- Generated by tt package build. Do not edit.\n")
	buf.WriteString("return {\n")
	fmt.Fprintf(&buf, "    package = { name = %s, version = %s, commit = %s, dirty = %t },\n",
		luaString(desc.Package), luaString(desc.Version.SemVer), luaString(desc.Version.Commit),
		desc.Version.Dirty)
	fmt.Fprintf(&buf, "    product = %s,\n", luaString(desc.Product))

	if len(desc.Rocks) == 0 {
		buf.WriteString("    rocks = {},\n")
		buf.WriteString("}\n")

		return buf.String()
	}

	rocks := slices.SortedFunc(slices.Values(desc.Rocks), func(a, b manifest.LockDependency) int {
		return cmp.Compare(a.Name, b.Name)
	})

	keys := make([]string, len(rocks))
	width := 0

	for i, rock := range rocks {
		keys[i] = luaKey(rock.Name)
		width = max(width, len(keys[i]))
	}

	buf.WriteString("    rocks = {\n")

	for i, rock := range rocks {
		fmt.Fprintf(&buf, "        %-*s = { version = %s, source = %s },\n",
			width, keys[i], luaString(rock.Version), luaString(rock.Source))
	}

	buf.WriteString("    },\n")
	buf.WriteString("}\n")

	return buf.String()
}

// luaKey renders name as the key of a field of a table constructor: bare when
// it is a Lua name, ["name"] otherwise - a rock name with a dash or a dot, or
// a keyword.
func luaKey(name string) string {
	if luaIdentRe.MatchString(name) && !slices.Contains(luaKeywords, name) {
		return name
	}

	return "[" + luaString(name) + "]"
}
