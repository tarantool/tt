package systemd

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"path/filepath"
	"strconv"
	"strings"
	"text/template"
	"time"

	"github.com/tarantool/tt/v3/internal/instances"
)

const (
	// GeneratedHeader starts every file tt writes (IsGenerated).
	GeneratedHeader = "# Generated by tt service systemd"
	// UnitEnv is the variable the template unit sets to the name of the
	// unit, %n: tt instance start --foreground started with it is the start
	// the unit of the instance asks for, which the instance commands do not
	// refuse.
	UnitEnv = "TT_SYSTEMD_UNIT"
	// DefaultRunAs is the user and the group the units run the instances as
	// by default: the system user the deb and rpm packages of tt create, as
	// the units tt2 packed ran them.
	DefaultRunAs = "tarantool"
	// DropInName is the name of the drop-in of an instance in its drop-in
	// directory.
	DropInName = "tt.conf"

	// serviceSuffix is the type suffix of a service unit.
	serviceSuffix = ".service"
	// unitNameMax is the longest unit name systemd takes.
	unitNameMax = 255
)

var (
	// ErrUnitName is wrapped by the error for an application or an instance
	// whose name cannot go into the name of a unit as it is.
	ErrUnitName = errors.New("cannot name a systemd unit")
	// ErrUnitPath is wrapped by the error for a path that cannot go into a
	// unit as it is.
	ErrUnitPath = errors.New("cannot be written into a systemd unit")
	// ErrUnitAccount is wrapped by the error for a user or a group whose
	// name cannot go into a unit as it is.
	ErrUnitAccount = errors.New("cannot be written into a systemd unit")
	// errRestartPolicy is wrapped by the error for a restart policy that has
	// no Restart= of the same name.
	errRestartPolicy = errors.New("unknown restart policy")
)

var (
	//go:embed templates/unit.service.tmpl
	unitTemplateText string
	//go:embed templates/dropin.conf.tmpl
	dropInTemplateText string

	unitTemplate   = template.Must(template.New("unit").Parse(unitTemplateText))
	dropInTemplate = template.Must(template.New("dropin").Parse(dropInTemplateText))
)

// RunAs is the user and the group the units run the instances as, User= and
// Group= of the template.
type RunAs struct {
	// User is the name or the numeric id of the user.
	User string
	// Group is the name or the numeric id of the group.
	Group string
}

// ParseRunAs parses <user>[:<group>]; without a group the group is the
// user's name. A name is made of what a unit takes without escaping
// (checkAccount).
func ParseRunAs(value string) (RunAs, error) {
	userName, group, found := strings.Cut(value, ":")
	if !found {
		group = userName
	}

	runAs := RunAs{User: userName, Group: group}

	err := runAs.check()
	if err != nil {
		return RunAs{}, err
	}

	return runAs, nil
}

// String returns the user and the group as ParseRunAs takes them,
// <user>:<group>.
func (runAs RunAs) String() string {
	return runAs.User + ":" + runAs.Group
}

// check checks that the user and the group can go into a unit as they are.
func (runAs RunAs) check() error {
	for _, account := range [...]struct{ what, name string }{
		{"user", runAs.User}, {"group", runAs.Group},
	} {
		err := checkAccount(account.what, account.name)
		if err != nil {
			return err
		}
	}

	return nil
}

// Units is what the units of an application are made of.
type Units struct {
	// App is the name of the application.
	App string
	// RunAs is the user and the group the units run the instances as.
	RunAs RunAs
	// Root is the root of the system scope the application is installed in,
	// which the units pass to tt as TT_SYSTEM_ROOT.
	Root string
	// TT is the tt executable the units run, an absolute path.
	TT string
	// StopTimeout is TimeoutStopSec= of the template, for an instance without
	// a drop-in: how long systemd waits for tt to stop an instance whose
	// record sets no stop_timeout.
	StopTimeout time.Duration
	// Instances are the instances of the application, in the order of its
	// description.
	Instances []Instance
}

// Instance is what the drop-in of an instance is made of.
type Instance struct {
	// Name is the name of the instance.
	Name string
	// Restart is the restart field of its record.
	Restart instances.RestartPolicy
	// StopTimeout is TimeoutStopSec= of the instance: how long systemd waits
	// for tt to stop it before it kills what is left.
	StopTimeout time.Duration
}

// File is a file of the units.
type File struct {
	// Name is the path of the file relative to the unit directory.
	Name string
	// Content is what the file holds.
	Content []byte
}

// TemplateName returns the name of the template unit of the application
// app, <app>@.service.
func TemplateName(app string) string {
	return app + "@" + serviceSuffix
}

// UnitName returns the name of the unit of the instance inst of the
// application app, <app>@<inst>.service.
func UnitName(app, inst string) string {
	return app + "@" + inst + serviceSuffix
}

// DropInPath returns the path of the drop-in of the unit, relative to the
// unit directory: <unit>.d/tt.conf.
func DropInPath(unit string) string {
	return filepath.Join(unit+".d", DropInName)
}

// IsGenerated reports whether content is that of a file tt wrote.
func IsGenerated(content []byte) bool {
	return bytes.HasPrefix(content, []byte(GeneratedHeader))
}

// Generate returns the files of units: the template unit, then the drop-in
// of every instance, in their order.
//
// A name or a path that a unit would have to escape or quote is an error
// rather than escaped: %i passes the instance name to tt as the unit name
// has it, so a name must be one that needs no escaping in a unit name, and
// the paths go into ExecStart= and Environment= as they are.
func Generate(units Units) ([]File, error) {
	err := checkUnits(units)
	if err != nil {
		return nil, err
	}

	var unit bytes.Buffer

	err = unitTemplate.Execute(&unit, map[string]string{
		"Header":      GeneratedHeader,
		"App":         units.App,
		"Template":    TemplateName(units.App),
		"User":        units.RunAs.User,
		"Group":       units.RunAs.Group,
		"Root":        units.Root,
		"UnitEnv":     UnitEnv,
		"TT":          units.TT,
		"StopTimeout": seconds(units.StopTimeout),
	})
	if err != nil {
		return nil, fmt.Errorf("cannot render the unit of %q: %w", units.App, err)
	}

	files := []File{{Name: TemplateName(units.App), Content: unit.Bytes()}}

	for _, inst := range units.Instances {
		restart := inst.Restart
		if restart == "" {
			restart = instances.RestartNo
		}

		var dropIn bytes.Buffer

		err = dropInTemplate.Execute(&dropIn, map[string]string{
			"Header":      GeneratedHeader,
			"App":         units.App,
			"Instance":    inst.Name,
			"Restart":     string(restart),
			"StopTimeout": seconds(inst.StopTimeout),
		})
		if err != nil {
			return nil, fmt.Errorf("cannot render the drop-in of %q: %w", inst.Name, err)
		}

		files = append(files, File{
			Name:    DropInPath(UnitName(units.App, inst.Name)),
			Content: dropIn.Bytes(),
		})
	}

	return files, nil
}

// checkUnits checks that units can be written as they are.
func checkUnits(units Units) error {
	err := checkName("application", units.App, prefixChar)
	if err != nil {
		return err
	}

	// The target <app>:%i is an argument of tt: one that starts with a dash
	// would be taken for a flag.
	if strings.HasPrefix(units.App, "-") {
		return fmt.Errorf("application %q %w: it starts with a dash", units.App, ErrUnitName)
	}

	err = units.RunAs.check()
	if err != nil {
		return err
	}

	for _, path := range [...]struct{ what, path string }{
		{"the root of the system scope", units.Root},
		{"the tt executable", units.TT},
	} {
		err = checkPath(path.what, path.path)
		if err != nil {
			return err
		}
	}

	for _, inst := range units.Instances {
		err = checkName("instance", inst.Name, instanceChar)
		if err != nil {
			return err
		}

		if len(UnitName(units.App, inst.Name)) > unitNameMax {
			return fmt.Errorf("instance %q of %q %w: %s is longer than %d characters",
				inst.Name, units.App, ErrUnitName, UnitName(units.App, inst.Name), unitNameMax)
		}

		switch inst.Restart {
		case "", instances.RestartNo, instances.RestartOnFailure, instances.RestartAlways:
		default:
			return fmt.Errorf("instance %q of %q: %w %q", inst.Name, units.App,
				errRestartPolicy, inst.Restart)
		}
	}

	return nil
}

// prefixChar reports whether char may be in the name of an application, the
// prefix of a unit name: a letter, a digit, "_", "." or "-". ":" is left
// out: it ends the application in a target.
func prefixChar(char rune) bool {
	return 'a' <= char && char <= 'z' || 'A' <= char && char <= 'Z' ||
		'0' <= char && char <= '9' || strings.ContainsRune("_.-", char)
}

// instanceChar reports whether char may be in the name of an instance, the
// instance of a unit name, as systemd takes it without escaping: what a
// prefix takes, ":" and "@".
func instanceChar(char rune) bool {
	return prefixChar(char) || char == ':' || char == '@'
}

// checkName checks that name, the name of what, is made of the characters
// valid says a unit name takes without escaping.
func checkName(what, name string, valid func(rune) bool) error {
	if name == "" {
		return fmt.Errorf("an empty %s name %w", what, ErrUnitName)
	}

	for _, char := range name {
		if !valid(char) {
			return fmt.Errorf("%s %q %w: %q would need escaping", what, name, ErrUnitName,
				char)
		}
	}

	return nil
}

// checkAccount checks that name, the name of a user or a group as what says,
// can go into User= or Group= as it is: what an application name takes
// (prefixChar), a numeric id among them, but not a dash first, which systemd
// refuses.
func checkAccount(what, name string) error {
	if name == "" {
		return fmt.Errorf("an empty %s name %w", what, ErrUnitAccount)
	}

	if strings.HasPrefix(name, "-") {
		return fmt.Errorf("%s %q %w: it starts with a dash", what, name, ErrUnitAccount)
	}

	for _, char := range name {
		if !prefixChar(char) {
			return fmt.Errorf("%s %q %w: %q would need escaping", what, name, ErrUnitAccount,
				char)
		}
	}

	return nil
}

// checkPath checks that path, the path of what, is absolute and needs no
// quoting in ExecStart= and Environment=: letters, digits and "/._-+@:,~".
// A space, a quote, a backslash, "%" and "$" would.
func checkPath(what, path string) error {
	if !filepath.IsAbs(path) {
		return fmt.Errorf("%s %q %w: it is not an absolute path", what, path, ErrUnitPath)
	}

	for _, char := range path {
		if prefixChar(char) || strings.ContainsRune("/+@:,~", char) {
			continue
		}

		return fmt.Errorf("%s %q %w: %q would need quoting", what, path, ErrUnitPath, char)
	}

	return nil
}

// seconds formats timeout for TimeoutStopSec=: whole seconds, rounded up, so
// that systemd never waits less than timeout.
func seconds(timeout time.Duration) string {
	whole := (timeout + time.Second - 1) / time.Second

	return strconv.FormatInt(int64(whole), 10) + "s"
}
