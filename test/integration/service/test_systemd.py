import json
import os
import signal
import subprocess

import pytest
from integration.service.service_helpers import install_app

import utils

# The units of myapp: the template and the drop-ins of its instances, by their
# paths in the unit directory.
UNIT_FILES = [
    "myapp@.service",
    "myapp@api.service.d/tt.conf",
    "myapp@worker.service.d/tt.conf",
]


@pytest.fixture
def system_root(tmp_path, tt_cmd):
    """A system root with myapp installed and tt of the scope."""
    root = tmp_path / "root"
    install_app(root, tt_cmd)
    return root


def tt_env(root, **extra):
    """The environment of tt with the system root root, outside of any unit,
    with extra on top."""
    env = dict(os.environ, TT_SYSTEM_ROOT=str(root))
    env.pop("TT_SYSTEMD_UNIT", None)
    env.update(extra)
    return env


def run(tt_cmd, root, *args, cwd=None, **extra):
    """Run tt with args and the system root root; return the exit code and the
    output, with the error output."""
    return utils.run_command_and_get_output(
        [tt_cmd, *args],
        cwd=cwd or root,
        env=tt_env(root, **extra),
    )


def unit_files(unit_dir):
    """Return the files under unit_dir, relative to it."""
    return sorted(
        os.path.relpath(os.path.join(dirpath, name), unit_dir)
        for dirpath, _, names in os.walk(unit_dir)
        for name in names
    )


def status(tt_cmd, root):
    """Return tt instance status of myapp as JSON."""
    rc, out = utils.run_command_and_get_output(
        [tt_cmd, "instance", "status", "myapp:*", "-o", "json"],
        cwd=root,
        env=tt_env(root),
        stderr=subprocess.DEVNULL,
    )
    assert rc == 0, out
    return json.loads(out)


def test_systemd_generate(tt_cmd, system_root, tmp_path):
    # generate prints the units, each after a line naming it, and writes
    # nothing into the system.
    rc, out = run(tt_cmd, system_root, "service", "systemd", "generate", "myapp")
    assert rc == 0, out
    assert "==> myapp@.service <==\n" in out
    assert (
        f"ExecStart={system_root}/bin/tt instance start --foreground --scope system myapp:%i\n"
    ) in out
    assert f"Environment=TT_SYSTEM_ROOT={system_root}\n" in out
    assert "Environment=TT_SYSTEMD_UNIT=%n\n" in out
    assert "KillMode=mixed\n" in out
    assert (
        "==> myapp@worker.service.d/tt.conf <==\n"
        "# Generated by tt service systemd: the instance worker of myapp,\n"
        "# from restart and stop_timeout of its record in instances.yaml.\n"
        "# tt service systemd install writes this file anew.\n"
        "[Service]\nRestart=on-failure\nTimeoutStopSec=15s\n"
    ) in out
    assert "==> myapp@api.service.d/tt.conf <==" in out
    assert "Restart=always\nTimeoutStopSec=35s\n" in out
    assert not (system_root / "etc" / "myapp" / "systemd.yaml").exists()

    unit_dir = tmp_path / "generated"
    rc, out = run(
        tt_cmd,
        system_root,
        "service",
        "systemd",
        "generate",
        "myapp",
        "--unit-dir",
        str(unit_dir),
    )
    assert rc == 0, out
    assert unit_files(unit_dir) == UNIT_FILES
    assert not (system_root / "etc" / "myapp" / "systemd.yaml").exists()


@pytest.mark.parametrize("command", ["generate", "install", "uninstall"])
@pytest.mark.parametrize("scope", ["user", "project"])
def test_systemd_scope_not_supported(tt_cmd, system_root, tmp_path, command, scope):
    # Units are made for the system scope only.
    project = tmp_path / "myapp"
    (project / ".templates" / "default").mkdir(parents=True)
    (project / ".templates" / "default" / "instances.yaml").write_text("w:\n  binary: sh\n")

    rc, out = run(
        tt_cmd,
        system_root,
        "service",
        "systemd",
        command,
        "myapp",
        "--scope",
        scope,
        cwd=project,
        TT_USER_ROOT=str(tmp_path / "user"),
    )
    assert rc == 1, out
    assert "systemd units are made for the system scope only" in out

    if scope == "project":
        # The project of that name is what myapp names in it.
        rc, out = run(tt_cmd, system_root, "service", "systemd", command, "myapp", cwd=project)
        assert rc == 1, out
        assert "pass --scope system" in out


@pytest.mark.parametrize("command", ["generate", "install"])
def test_systemd_not_installed(tt_cmd, system_root, command):
    # An application the system scope does not have is to be installed
    # there: units are made for no other scope.
    rc, out = run(tt_cmd, system_root, "service", "systemd", command, "other")
    assert rc == 1, out
    assert (
        f'"other" is not installed in the system scope in {system_root}; '
        "install it with tt package install --scope system <ARCHIVE>"
    ) in out
    assert "pass --scope" not in out


def test_systemd_install_uninstall(tt_cmd, system_root, tmp_path):
    # install writes the units and the mark; the instance commands that start
    # and stop instances refuse those of the units, status shows the units;
    # uninstall removes both.
    unit_dir = tmp_path / "units"
    unit_dir.mkdir()

    rc, out = run(
        tt_cmd,
        system_root,
        "service",
        "systemd",
        "install",
        "myapp",
        "--unit-dir",
        str(unit_dir),
    )
    assert rc == 0, out
    assert unit_files(unit_dir) == UNIT_FILES
    assert "systemctl daemon-reload\n" in out
    assert "systemctl enable --now myapp@worker.service myapp@api.service\n" in out

    mark = (system_root / "etc" / "myapp" / "systemd.yaml").read_text()
    assert f"unit_dir: {unit_dir}\n" in mark
    assert "template: myapp@.service\n" in mark
    assert "  worker: myapp@worker.service\n" in mark

    got = status(tt_cmd, system_root)
    assert got["myapp:worker"]["unit"] == "myapp@worker.service"
    assert got["myapp:api"]["unit"] == "myapp@api.service"
    assert got["myapp:worker"]["status"] == "NOT RUNNING"

    rc, out = run(tt_cmd, system_root, "instance", "status", "myapp:*")
    assert rc == 0, out
    assert "UNIT" in out
    assert "myapp@worker.service" in out

    for command, systemctl in [
        (["start"], "start"),
        (["stop", "--yes"], "stop"),
        (["restart", "--yes"], "restart"),
        (["kill", "--yes"], "kill --signal=SIGKILL"),
        (["start", "--foreground"], "start"),
    ]:
        rc, out = run(tt_cmd, system_root, "instance", *command, "myapp:worker")
        assert rc == 1, out
        assert (
            "myapp:worker is managed by systemd through the unit myapp@worker.service: "
            f"use systemctl {systemctl} myapp@worker.service"
        ) in out

    assert not os.path.exists(os.path.join(system_root, "var", "run", "myapp", "worker", "tt.pid"))

    # Commands that neither start nor stop an instance act on it.
    rc, out = run(tt_cmd, system_root, "instance", "clean", "--yes", "myapp:worker")
    assert rc == 0, out

    rc, out = run(tt_cmd, system_root, "service", "systemd", "uninstall", "myapp")
    assert rc == 0, out
    assert "systemctl daemon-reload" in out
    assert unit_files(unit_dir) == []
    assert not (system_root / "etc" / "myapp" / "systemd.yaml").exists()
    assert "unit" not in status(tt_cmd, system_root)["myapp:worker"]

    # Units that are not installed are nothing to remove: no failure, and
    # nothing is touched.
    rc, out = run(tt_cmd, system_root, "service", "systemd", "uninstall", "myapp")
    assert rc == 0, out
    assert "The systemd units of myapp are not installed" in out
    assert "systemctl" not in out
    assert unit_files(unit_dir) == []

    # A mark that cannot be read may name units: it is an error.
    (system_root / "etc" / "myapp" / "systemd.yaml").write_text("units: [\n")
    rc, out = run(tt_cmd, system_root, "service", "systemd", "uninstall", "myapp")
    assert rc == 1, out
    assert "invalid mark of systemd units" in out


def test_systemd_run_as(tt_cmd, system_root, tmp_path):
    # --run-as sets User= and Group=; install records it, and an install that
    # names none keeps it.
    rc, out = run(
        tt_cmd,
        system_root,
        "service",
        "systemd",
        "generate",
        "myapp",
        "--run-as",
        "tt-svc:daemon",
    )
    assert rc == 0, out
    assert "\nUser=tt-svc\nGroup=daemon\n" in out

    unit_dir = tmp_path / "units"
    unit_dir.mkdir()
    install = ["service", "systemd", "install", "myapp", "--unit-dir", str(unit_dir)]
    mark = system_root / "etc" / "myapp" / "systemd.yaml"
    template = unit_dir / "myapp@.service"

    rc, out = run(tt_cmd, system_root, *install, "--run-as", "tt-no-such-user")
    assert rc == 0, out
    assert "run as tt-no-such-user:tt-no-such-user" in out
    assert "the user tt-no-such-user, which this host does not have" in out
    assert "the group tt-no-such-user, which this host does not have" in out
    assert "\nUser=tt-no-such-user\nGroup=tt-no-such-user\n" in template.read_text()
    assert "\nrun_as: tt-no-such-user:tt-no-such-user\n" in mark.read_text()

    rc, out = run(tt_cmd, system_root, *install)
    assert rc == 0, out
    assert "\nUser=tt-no-such-user\nGroup=tt-no-such-user\n" in template.read_text()

    rc, out = run(tt_cmd, system_root, *install, "--run-as", "tarantool")
    assert rc == 0, out
    assert "\nUser=tarantool\nGroup=tarantool\n" in template.read_text()
    assert "\nrun_as: tarantool:tarantool\n" in mark.read_text()

    rc, out = run(tt_cmd, system_root, *install, "--run-as", "tt svc")
    assert rc == 1, out
    assert 'user "tt svc" cannot be written into a systemd unit' in out
    assert "\nUser=tarantool\n" in template.read_text()


def test_systemd_install_refuses_foreign_unit(tt_cmd, system_root, tmp_path):
    # A unit of the same name that tt did not write is not tt's to replace.
    unit_dir = tmp_path / "units"
    unit_dir.mkdir()
    (unit_dir / "myapp@.service").write_text("[Service]\nExecStart=/bin/true\n")

    rc, out = run(
        tt_cmd,
        system_root,
        "service",
        "systemd",
        "install",
        "myapp",
        "--unit-dir",
        str(unit_dir),
    )
    assert rc == 1, out
    assert "was not written by tt service systemd" in out
    assert unit_files(unit_dir) == ["myapp@.service"]
    assert not (system_root / "etc" / "myapp" / "systemd.yaml").exists()


def test_systemd_unit_starts_its_instance(tt_cmd, system_root, tmp_path):
    # The unit runs tt instance start --foreground, which TT_SYSTEMD_UNIT
    # tells from a start next to the unit: it is not refused, and the
    # instance runs as one started by tt does.
    unit_dir = tmp_path / "units"
    unit_dir.mkdir()

    rc, out = run(
        tt_cmd,
        system_root,
        "service",
        "systemd",
        "install",
        "myapp",
        "--unit-dir",
        str(unit_dir),
    )
    assert rc == 0, out

    # Another unit is not the unit of the instance.
    rc, out = run(
        tt_cmd,
        system_root,
        "instance",
        "start",
        "--foreground",
        "--scope",
        "system",
        "myapp:worker",
        TT_SYSTEMD_UNIT="myapp@api.service",
    )
    assert rc == 1, out
    assert "use systemctl start myapp@worker.service" in out

    unit = subprocess.Popen(
        [tt_cmd, "instance", "start", "--foreground", "--scope", "system", "myapp:worker"],
        cwd="/",
        env=tt_env(system_root, TT_SYSTEMD_UNIT="myapp@worker.service"),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    try:
        pid_file = system_root / "var" / "run" / "myapp" / "worker" / "tt.pid"
        assert utils.wait_files(10, [str(pid_file)])
        assert utils.wait_event(
            10,
            lambda: status(tt_cmd, system_root)["myapp:worker"]["status"] == "RUNNING",
        )
        assert status(tt_cmd, system_root)["myapp:worker"]["unit"] == "myapp@worker.service"

        rc, out = run(tt_cmd, system_root, "instance", "stop", "--yes", "myapp:worker")
        assert rc == 1, out
        assert "use systemctl stop myapp@worker.service" in out

        rc, out = run(tt_cmd, system_root, "instance", "logrotate", "myapp:worker")
        assert rc == 0, out

        # The units of a running instance stay.
        rc, out = run(tt_cmd, system_root, "service", "systemd", "uninstall", "myapp")
        assert rc == 1, out
        assert "systemctl disable --now myapp@worker.service" in out
        assert unit_files(unit_dir) == UNIT_FILES

        # The stop of systemd: SIGTERM to tt alone.
        unit.send_signal(signal.SIGTERM)
        out, _ = unit.communicate(timeout=30)
        assert unit.returncode == 0, out
        assert "worker got TERM" in out
    finally:
        if unit.poll() is None:
            unit.kill()
            unit.wait()

    assert status(tt_cmd, system_root)["myapp:worker"]["status"] == "NOT RUNNING"

    rc, out = run(tt_cmd, system_root, "service", "systemd", "uninstall", "myapp")
    assert rc == 0, out
    assert unit_files(unit_dir) == []


def test_systemd_install_again(tt_cmd, system_root, tmp_path):
    # install again follows the description: the drop-in of an instance that
    # is gone goes, and a new one comes.
    unit_dir = tmp_path / "units"
    unit_dir.mkdir()

    args = ["service", "systemd", "install", "myapp", "--unit-dir", str(unit_dir)]
    rc, out = run(tt_cmd, system_root, *args)
    assert rc == 0, out

    (system_root / "etc" / "myapp" / "instances.yaml").write_text(
        "worker:\n  binary: ./worker.sh\n  restart: always\njob:\n  binary: ./worker.sh\n",
    )

    rc, out = run(tt_cmd, system_root, *args)
    assert rc == 0, out
    assert "myapp@api.service" in out
    assert "systemctl disable --now myapp@api.service" in out
    assert unit_files(unit_dir) == [
        "myapp@.service",
        "myapp@job.service.d/tt.conf",
        "myapp@worker.service.d/tt.conf",
    ]
    assert "Restart=always\n" in (unit_dir / "myapp@worker.service.d" / "tt.conf").read_text()

    # The units are elsewhere: uninstall them first.
    other = tmp_path / "other"
    other.mkdir()
    rc, out = run(tt_cmd, system_root, *args[:-1], str(other))
    assert rc == 1, out
    assert "uninstall them with tt service systemd uninstall myapp first" in out
